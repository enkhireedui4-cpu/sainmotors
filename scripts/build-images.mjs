async function ensureDir(dir) {
  await fs.mkdir(dir, { recursive: true });
}

async function averageColor(pipeline) {
  const { dominant } = await pipeline.clone().stats();
  const hex = (n) => n.toString(16).padStart(2, "0");
  return `#${hex(dominant.r)}${hex(dominant.g)}${hex(dominant.b)}`;
}

async function buildPhoto(key, { file, crop, area }) {
  let base = sharp(path.join(SRC, "photos", file)).rotate();
  const meta = await base.metadata();
  if (area) {
    const [x, y, w, h] = area;
    crop = {
      left: Math.round(x * meta.width),
      top: Math.round(y * meta.height),
      width: Math.min(Math.round(w * meta.width), meta.width - Math.round(x * meta.width)),
      height: Math.min(Math.round(h * meta.height), meta.height - Math.round(y * meta.height)),
    };
  }
  if (crop) base = base.extract(crop);
  const width = crop ? crop.width : meta.width;
  const height = crop ? crop.height : meta.height;
  const top = WIDTHS[WIDTHS.length - 1];
  const widths = WIDTHS.filter((w) => w < width).concat(width > top ? [] : [width]);
  const srcset = [];
  for (const w of [...new Set(widths)]) {
    const name = `${key}-${w}.webp`;
    await base.clone().resize({ width: w }).webp({ quality: 72, effort: 5 }).toFile(path.join(OUT, name));
    srcset.push([w, `/media/${name}`]);
  }
  return { width, height, color: await averageColor(base), srcset };
}

/** Split an alpha mask into horizontal ink bands separated by empty rows. */
function findBands(mask, w, h, gapRatio = 0.03) {
  const rows = new Array(h).fill(false);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (mask[y * w + x] > 40) {
        rows[y] = true;
        break;
      }
    }
  }
  const minGap = Math.max(3, Math.round(h * gapRatio));
  const bands = [];
  let start = -1;
  let gap = 0;
  for (let y = 0; y < h; y++) {
    if (rows[y]) {
      if (start === -1) start = y;
      gap = 0;
    } else if (start !== -1) {
      gap++;
      if (gap >= minGap) {
        bands.push([start, y - gap]);
        start = -1;
        gap = 0;
      }
    }
  }
  if (start !== -1) bands.push([start, h - 1 - gap]);
  return bands;
}

async function buildLogo(slug, { file, band, mask, ink: inkMode, gap, area, optical = 1 }) {
  const input = path.join(SRC, "logos", file);
  const isSvg = file.endsWith(".svg");
  // Rasterise SVGs at ~2400 px wide whatever their canvas size.
  const svgDensity = isSvg ? Math.min(7200, (72 * 2400) / (await sharp(input).metadata()).width) : undefined;
  const raw = sharp(input, isSvg ? { density: svgDensity } : {})
    .resize({ width: 2400, withoutEnlargement: !isSvg })
    .ensureAlpha();
  const { data, info } = await raw.raw().toBuffer({ resolveWithObject: true });
  const { width: w, height: h } = info;
  const m = Buffer.alloc(w * h);
  for (let i = 0; i < w * h; i++) {
    const r = data[i * 4];
    const g = data[i * 4 + 1];
    const b = data[i * 4 + 2];
    const a = data[i * 4 + 3];
    const x = i % w;
    const y = Math.floor(i / w);
    const inside = !area || (x >= area[0] * w && x < (area[0] + area[2]) * w && y >= area[1] * h && y < (area[1] + area[3]) * h);
    m[i] = inside ? (mask === "luma" ? Math.round(((0.2126 * r + 0.7152 * g + 0.0722 * b) * a) / 255) : a) : 0;
  }
  const bands = findBands(m, w, h, gap);
  if (!bands.length) throw new Error(`No ink found in ${file}`);
  if (typeof band === "number" && !bands[band]) throw new Error(`${file}: band ${band} not found (${bands.length} bands)`);
  const [top, bottom] =
    typeof band === "number"
      ? bands[band]
      : band === "first"
        ? bands[0]
        : band === "last"
          ? bands[bands.length - 1]
          : [bands[0][0], bands[bands.length - 1][1]];

  let minX = w;
  let maxX = 0;
  for (let y = top; y <= bottom; y++) {
    for (let x = 0; x < w; x++) {
      if (m[y * w + x] > 40) {
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
      }
    }
  }
  const cw = maxX - minX + 1;
  const ch = bottom - top + 1;
  const out = Buffer.alloc(cw * ch * 4);
  let ink = 0;
  const sum = [0, 0, 0];
  for (let y = 0; y < ch; y++) {
    for (let x = 0; x < cw; x++) {
      const i = (y + top) * w + (x + minX);
      const a = m[i];
      const o = (y * cw + x) * 4;
      const rgb = [data[i * 4], data[i * 4 + 1], data[i * 4 + 2]];
      out[o] = rgb[0];
      out[o + 1] = rgb[1];
      out[o + 2] = rgb[2];
      out[o + 3] = a;
      ink += a / 255;
      for (let c = 0; c < 3; c++) sum[c] += (rgb[c] * a) / 255;
    }
  }
  const density = ink / (cw * ch);
  const color = "#" + sum.map((v) => Math.round(v / ink).toString(16).padStart(2, "0")).join("");
  // ~4x the largest display size; keeps files small without visible softening.
  const targetH = Math.min(ch, Math.round(Math.min(160, (640 * ch) / cw)));
  const name = `brand-${slug}.png`;
  const meta = await sharp(out, { raw: { width: cw, height: ch, channels: 4 } })
    .resize({ height: targetH })
    .png({ compressionLevel: 9 })
    .toFile(path.join(OUT, name));
  return { src: `/media/${name}`, width: meta.width, height: meta.height, density: +density.toFixed(3), optical, color, ink: inkMode };
}

async function buildSainLogo(key, file) {
  const name = `${key}.png`;
  const meta = await sharp(path.join(SRC, "logos", file))
    .trim()
    .resize({ height: 120 })
    .png({ compressionLevel: 9 })
    .toFile(path.join(OUT, name));
  return { src: `/media/${name}`, width: meta.width, height: meta.height };
}

async function buildSocialImage() {
  const W = 1200;
  const H = 630;
  const logo = await sharp(path.join(SRC, "logos", "sain-on-dark.png")).trim().resize({ width: 300 }).toBuffer();
  const photo = await sharp(path.join(SRC, "photos", "showroom-6.webp"))
    .extract({ left: 560, top: 380, width: 2000, height: 1050 })
    .resize(W, H, { fit: "cover" })
    .toBuffer();
  const shade = Buffer.from(
    `<svg width="${W}" height="${H}"><defs><linearGradient id="g" x1="0" y1="0" x2="0" y2="1"><stop offset="0.55" stop-color="#000" stop-opacity="0"/><stop offset="1" stop-color="#000" stop-opacity="0.55"/></linearGradient></defs><rect width="100%" height="100%" fill="url(#g)"/></svg>`,
  );
  await sharp(photo)
    .composite([{ input: shade }, { input: logo, left: 56, top: H - 56 - 88 }])
    .jpeg({ quality: 82, mozjpeg: true })
    .toFile(path.join(OUT, "social-default.jpg"));
  return { src: "/media/social-default.jpg", width: W, height: H };
}

